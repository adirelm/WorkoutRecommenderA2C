"""Tests for src/model/trajectory_builder.py — synthetic-trainee rollouts (brief §7.3).

Phase-3 bridge between Phase-1 daily_aggregate and Phase-2 WorkoutEnv:
the LSTM world model is trained on (state, action, next_state) triples
generated by rolling the env under a fixed baseline policy.
"""

from __future__ import annotations

import pytest

from src.env.action_mask import ActionMaskService
from src.env.state import ACTION_COUNT, State
from src.env.workout_env import WorkoutEnv
from src.model.trajectory_builder import generate_trajectory


def test_generate_trajectory_length_matches_num_days() -> None:
    traj = generate_trajectory(num_days=28, seed=42)
    assert len(traj) == 28


def test_states_are_state_dataclass_instances() -> None:
    traj = generate_trajectory(num_days=10, seed=42)
    for s, _a, ns in traj:
        assert isinstance(s, State)
        assert isinstance(ns, State)


def test_actions_in_range_0_to_6() -> None:
    traj = generate_trajectory(num_days=28, seed=42)
    for _s, a, _ns in traj:
        assert isinstance(a, int)
        assert 0 <= a < ACTION_COUNT


def test_seeded_trajectory_deterministic() -> None:
    traj_a = generate_trajectory(num_days=14, seed=7)
    traj_b = generate_trajectory(num_days=14, seed=7)
    assert len(traj_a) == len(traj_b)
    for (sa, aa, nsa), (sb, ab, nsb) in zip(traj_a, traj_b, strict=True):
        assert sa == sb
        assert aa == ab
        assert nsa == nsb


def test_rotate_chains_visits_each_chain_at_least_once_per_week() -> None:
    """Deterministic PPL cycle: across any 7-day window every action in
    (0=Rest, 1=Push, 2=Pull, 3=Legs, 6=Mobility, 4=FullBody, 5=Conditioning)
    should appear at least once."""
    traj = generate_trajectory(num_days=7, seed=42, action_policy="rotate_chains")
    actions = {a for _s, a, _ns in traj}
    assert actions == {0, 1, 2, 3, 4, 5, 6}


def test_uniform_random_masked_obeys_action_mask() -> None:
    """No action chosen by the random-masked policy may be an illegal action."""
    env = WorkoutEnv(seed=42)
    mask_service = ActionMaskService()
    env.reset()
    traj = generate_trajectory(num_days=28, seed=42, action_policy="uniform_random_masked")
    # Replay the same env to recover the per-step legality mask.
    env2 = WorkoutEnv(seed=42)
    state = env2.reset()
    history: list[int] = []
    for s, a, _ns in traj:
        assert s == state, "trajectory state must match env replay"
        mask = mask_service.mask(state, history)
        assert bool(mask[a]) is True, f"action {a} is illegal at step (mask={mask})"
        state, _r, _d, _i = env2.step(a)
        history.append(a)


def test_invalid_policy_raises() -> None:
    with pytest.raises(ValueError, match="action_policy"):
        generate_trajectory(num_days=5, seed=42, action_policy="not_a_policy")
